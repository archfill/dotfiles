#!/usr/bin/env bash

# Git personal configuration setup.
#
# This script intentionally keeps user.name / user.email out of tracked Nix
# files. It creates config/personal.conf interactively when needed, then writes
# the effective Git local config to ~/.config/git/config.local.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/lib/common.sh"
source "${SCRIPT_DIR}/lib/config_loader.sh"

setup_error_handling

log_info "Configuring Git settings"

DOTFILES_DIR="$(get_dotfiles_root)"
VERSIONS_CONFIG="${DOTFILES_DIR}/config/versions.conf"
PERSONAL_CONFIG="${DOTFILES_DIR}/config/personal.conf"
LOCAL_GITCONFIG="${HOME}/.config/git/config.local"

if [[ -f "$VERSIONS_CONFIG" ]]; then
  log_info "Loading versions configuration from $VERSIONS_CONFIG"
  source "$VERSIONS_CONFIG"
else
  log_warning "Versions configuration file not found: $VERSIONS_CONFIG"
fi

if [[ -f "$PERSONAL_CONFIG" ]]; then
  log_info "Loading personal configuration from $PERSONAL_CONFIG"
  source "$PERSONAL_CONFIG"
fi

is_placeholder_value() {
  case "${1:-}" in
    "" | "Your Name" | "Your Full Name" | "your.email@example.com")
      return 0
      ;;
    *)
      return 1
      ;;
  esac
}

shell_quote() {
  printf "%q" "$1"
}

prompt_value() {
  local label="$1"
  local default_value="${2:-}"
  local value

  if [[ -n "$default_value" ]]; then
    read -r -p "${label} [${default_value}]: " value
    echo "${value:-$default_value}"
  else
    while true; do
      read -r -p "${label}: " value
      if [[ -n "$value" ]]; then
        echo "$value"
        return 0
      fi
      log_warning "${label} is required"
    done
  fi
}

write_personal_config() {
  mkdir -p "$(dirname "$PERSONAL_CONFIG")"
  {
    echo "# Personal configuration"
    echo "# This file is generated by bin/config.sh and is ignored by Git."
    echo
    printf "export USER_NAME=%s\n" "$(shell_quote "$USER_NAME")"
    printf "export USER_EMAIL=%s\n" "$(shell_quote "$USER_EMAIL")"
    printf "export GHQ_ROOT=%s\n" "$(shell_quote "$GHQ_ROOT")"
  } > "$PERSONAL_CONFIG"
  chmod 600 "$PERSONAL_CONFIG"
  log_success "Personal configuration saved: $PERSONAL_CONFIG"
}

setup_personal_config_interactively() {
  if [[ ! -t 0 ]]; then
    log_error "config/personal.conf is missing or incomplete, and stdin is not interactive"
    log_info "Run this command in a terminal:"
    log_info "  make config"
    exit 1
  fi

  log_info "Starting interactive personal configuration"

  local current_git_name current_git_email default_ghq_root
  current_git_name="$(git config --file "$LOCAL_GITCONFIG" user.name 2>/dev/null || true)"
  current_git_email="$(git config --file "$LOCAL_GITCONFIG" user.email 2>/dev/null || true)"
  default_ghq_root="${GHQ_ROOT:-$HOME/git}"

  USER_NAME="$(prompt_value "Git user.name" "${USER_NAME:-$current_git_name}")"
  USER_EMAIL="$(prompt_value "Git user.email" "${USER_EMAIL:-$current_git_email}")"
  GHQ_ROOT="$(prompt_value "ghq.root" "$default_ghq_root")"

  write_personal_config
}

if is_placeholder_value "${USER_NAME:-}" || is_placeholder_value "${USER_EMAIL:-}"; then
  setup_personal_config_interactively
fi

if [[ -z "${GHQ_ROOT:-}" ]]; then
  GHQ_ROOT="$HOME/git"
fi

mkdir -p "$(dirname "$LOCAL_GITCONFIG")"
log_info "Setting up Git local configuration for: $USER_NAME <$USER_EMAIL>"

git config --file "$LOCAL_GITCONFIG" user.name "$USER_NAME"
git config --file "$LOCAL_GITCONFIG" user.email "$USER_EMAIL"

if [[ -n "${GHQ_ROOT:-}" ]]; then
  log_info "Setting ghq.root to ${GHQ_ROOT}"
  git config --file "$LOCAL_GITCONFIG" ghq.root "${GHQ_ROOT}"
fi

log_success "Git configuration completed (local: $LOCAL_GITCONFIG)"
